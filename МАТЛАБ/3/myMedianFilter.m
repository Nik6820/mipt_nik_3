function out = myMedianFilter(img, k)
% MYMEDIANFILTER Двумерная медианная фильтрация
%   img — входное изображение
%   k   — размер окна (нечётное: 3, 5, 7, ...)

    % Проверка: окно должно быть нечётным, иначе нет центрального пикселя
    if mod(k,2) == 0
        error('Размер окна k должен быть нечётным');
    end

    r = (k-1)/2;                       % радиус окна 
    [H, W, C] = size(img);             % размеры: высота, ширина, число каналов
    out = zeros(H, W, C, 'like', img); % выходной массив того же типа, что img

    % Дополняем края (репликация), чтобы окно не выходило за границы
    % 'replicate' — крайние пиксели дублируются, 'both' — с обеих сторон
    padded = padarray(img, [r r], 'replicate', 'both');

    for c = 1:C                        % перебор каналов (R, G, B)
        for i = 1:H                    % перебор строк
            for j = 1:W                % перебор столбцов
                % вырезаем окно k×k вокруг пикселя (i,j) в канале c
                window = padded(i:i+2*r, j:j+2*r, c);
                % медиана всех значений окна записывается в выходной пиксель
                out(i,j,c) = median(window(:));
            end
        end
    end
end