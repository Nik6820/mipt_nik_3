    (0,1,8.3), (1,2,11.2), (2,3,24.4), (3,4,17.9), (4,5,28.9),
    (5,6,16.3), (6,7,26.0), (7,8,26.3), (8,9,18.2), (9,10,23.1), (10,11,20.9)
