import numpy as np
import matplotlib.pyplot as plt

# ============================================================
# Параметры установки
# ============================================================
mu0 = 4 * np.pi * 1e-7
Nt0 = 1750          # витков намагничивающей обмотки тороида
Nt1 = 300           # витков измерительной обмотки тороида
D   = 0.10          # средний диаметр тора, м
dt  = 0.01          # диаметр сечения тора, м
Nc0 = 825           # витков намагничивающей обмотки соленоида
Nc1 = 435           # витков измерительной обмотки соленоида
dc  = 0.07          # диаметр соленоида, м
lc  = 0.8           # длина соленоида, м

# --- Сопротивления ---
R_T = 0.0           # сопротивление обмотки тороида (пренебрегаем)
R_C = 60.0          # сопротивление соленоида
R0  = 0.0           # сопротивление гальванометра (пренебрегаем)

R_M_second = 60.0   # сопротивление магазина во втором проходе
R_M_calib  = 10.0   # сопротивление магазина при калибровке

R_second = R_T + R_M_second + R0     # = 60 Ом
R_calib  = R_C + R_M_calib  + R0     # = 70 Ом

# --- Калибровка ---
dI_c = 1.4566       # А
dx_c = 9.3          # см

# --- Погрешности ---
delta_I = 0.001     # А
delta_x = 0.2       # см (2 мм)

# ============================================================
# Коэффициент пересчёта Δx -> ΔB
# ============================================================
K = mu0 * (dc/dt)**2 * (Nc1 * Nc0 / Nt1) * (R_second / R_calib) * (1/lc) * (dI_c / dx_c)
delta_K = K * np.sqrt((delta_I/dI_c)**2 + (delta_x/dx_c)**2)

print("=" * 60)
print("ПАРАМЕТРЫ РАСЧЁТА")
print("=" * 60)
print(f"R_T = {R_T} Ом,  R_C = {R_C} Ом")
print(f"R_second = {R_second} Ом,  R_calib = {R_calib} Ом,  R/R_c = {R_second/R_calib:.3f}")
print(f"K = ({K*1000:.3f} ± {delta_K*1000:.3f}) Тл/см × 10⁻³")
print(f"Погрешность ΔB на шаг: {K*delta_x*1000:.3f} мТл")
print(f"Погрешность H: {Nt0/(np.pi*D)*delta_I:.2f} А/м")
print("=" * 60)

# ============================================================
# Токи на ступенях
# ============================================================
I_steps = np.array([0, 0.0152, 0.0279, 0.0389, 0.0442, 0.0556,
                    0.0663, 0.0945, 0.1567, 0.2498, 0.5128, 1.4560])

